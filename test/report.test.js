it('the report prints what a run costs in money and time', () => {
  const priced = [
    { project: 'p1', sample: 's1', candidate: 'c', run: 1, verdict: 'caught', usd: 1, ms: 120000 },
    { project: 'p1', sample: 's1', candidate: 'c', run: 2, verdict: 'missed', usd: 0.5, ms: 240000 },
    { project: 'p1', sample: 's2', candidate: 'c', run: 1, verdict: 'missed' },
  ]
  const [summary] = summarize(priced)
  assert.deepEqual(summary.cost, { measured: 2, totalUsd: 1.5, usdPerRun: 0.75, minutesPerRun: 3 })
  assert.match(renderReport([summary]), /Cost: \$0\.75 per run, \$1\.50 in total over 2 measured runs · 3 min per run/)
})

it('comparePaired counts, per shared sample, which candidate caught more often', () => {
  const rows = [
    { project: 'p', sample: 'a', candidate: 'x', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'a', candidate: 'x', run: 2, verdict: 'caught' },
    { project: 'p', sample: 'a', candidate: 'y', run: 1, verdict: 'missed' },
    { project: 'p', sample: 'b', candidate: 'x', run: 1, verdict: 'missed' },
    { project: 'p', sample: 'b', candidate: 'y', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'c', candidate: 'x', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'c', candidate: 'y', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'd', candidate: 'x', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'e', candidate: 'y', run: 1, verdict: 'leaked' },
    { project: 'p', sample: 'e', candidate: 'x', run: 1, verdict: 'caught' },
  ]
  const paired = comparePaired(rows, 'x', 'y')
  assert.deepEqual(
    { wins: paired.wins, losses: paired.losses, ties: paired.ties, shared: paired.samples.length },
    { wins: 1, losses: 1, ties: 1, shared: 3 },
  )
  const text = renderPaired(paired)
  assert.match(text, /## x vs y\n\nOn 3 paired samples, broken counted as a miss: x catches more on 1, y on 1, tie on 1\./)
  assert.match(text, /\| p\/a \| 2\/2 \| 0\/1 \| x \|/)
})

it('comparePaired counts broken runs as misses and lists the samples it could not pair', () => {
  const rows = [
    { project: 'p', sample: 'a', candidate: 'x', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'a', candidate: 'x', run: 2, verdict: 'broken' },
    { project: 'p', sample: 'a', candidate: 'y', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'b', candidate: 'x', run: 1, verdict: 'broken' },
    { project: 'p', sample: 'b', candidate: 'y', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'c', candidate: 'x', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'c', candidate: 'y', run: 1, verdict: 'leaked' },
  ]
  const paired = comparePaired(rows, 'x', 'y')
  assert.deepEqual({ wins: paired.wins, losses: paired.losses, ties: paired.ties }, { wins: 0, losses: 2, ties: 0 })
  assert.match(renderPaired(paired), /\| p\/a \| 1\/2 \| 1\/1 \| y \|/)
  assert.match(renderPaired(paired), /Not paired \(no conclusive run for one of them\): p\/c/)
})

it('a catch below its layer is conclusive but not caught, and the report counts it apart', () => {
  const rows = [
    { project: 'p', sample: 'a', candidate: 'x', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'b', candidate: 'x', run: 1, verdict: 'caught-below-layer' },
    { project: 'p', sample: 'b', candidate: 'y', run: 1, verdict: 'caught' },
    { project: 'p', sample: 'a', candidate: 'y', run: 1, verdict: 'caught' },
  ]
  const [summary] = summarize(rows.filter((row) => row.candidate === 'x'))
  assert.deepEqual([summary.overall.caught, summary.overall.conclusive, summary.overall.belowLayer], [1, 2, 1])
  assert.match(renderReport([summary]), /Catch rate: 1\/2 \(50%\) · caught below their layer 1 · broken counted as misses/)
  assert.deepEqual(comparePaired(rows, 'x', 'y').samples.map((s) => [s.key, s.better]), [['p/a', 'tie'], ['p/b', 'y']])
})

function storeWithLabel(truth) {
  const root = tempDir()
  const sample = join(root, 'projects/p1/eval/s1')
  writeFile(sample, 'spec/feature.md', 'The toast hides after 5 seconds.\n')
  if (truth) writeFile(sample, 'truth.yaml', typeof truth === 'string' ? truth : stringify(truth))
  writeJson(join(sample, 'runs/s2t-1/verdict.json'), { verdict: 'missed' })
  writeJson(join(sample, 'runs/s2t-1/spec-to-tests/state.json'), { step: 'done' })
  writeFile(sample, 'runs/s2t-1/spec-to-tests/cases.yaml', stringify({ sentences: [{ id: 'S1', text: 'The toast hides after 5 seconds.', cases: [] }], cases: [] }))
  writeJson(join(sample, 'runs/plain-1/verdict.json'), { verdict: 'caught' })
  return root
}

const pick = (row) => ({ candidate: row.candidate, bucket: row.bucket, group: row.group, layer: row.layer, driver: row.driver })

it('attributeRecords puts each run in a bucket and a group', () => {
  const root = storeWithLabel({ bug_quote: 'hides after 5 seconds', reviewed: true })
  assert.deepEqual(attributeRecords(loadVerdicts(root), root).map(pick), [
    { candidate: 'plain', bucket: 'specified', group: 'caught', layer: null, driver: false },
    { candidate: 's2t', bucket: 'specified', group: 'missed@done', layer: 'qc-no-case', driver: true },
  ])
})

it('a sample with an unreviewed or broken truth.yaml is unlabelled and does not throw', () => {
  for (const truth of [{ bug_quote: 'hides after 5 seconds', reviewed: false }, 'bug_quote: [unclosed\n', null]) {
    const root = storeWithLabel(truth)
    const rows = attributeRecords(loadVerdicts(root), root)
    assert.deepEqual(rows.map((row) => [row.bucket, row.layer]), [['unlabelled', null], ['unlabelled', 'unattributed']])
  }
})

